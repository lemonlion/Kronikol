def parse_iso(text):
    if not text:
        return None
    import datetime as dt
    m = re.match(r"^(.*?\.\d{1,6})\d*(Z|[+-]\d\d:\d\d)?$", text.strip())
    text = (m.group(1) + (m.group(2) or "")) if m else text
    return dt.datetime.fromisoformat(text.replace("Z", "+00:00"))


def parse_clock(clock, on):
    """A compare.json clock ("17:53:09.628Z") on the date of `on`."""
    if not clock or not on or clock == "-":
        return None
    import datetime as dt
    h, m, s = clock.rstrip("Z").split(":")
    return on.replace(hour=int(h), minute=int(m), second=int(float(s)), microsecond=int(round((float(s) % 1) * 1_000_000)) % 1_000_000)


