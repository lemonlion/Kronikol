def theory_cells(c):
    """For rows 1..6: (row whose name the scenario holding the row's call carries, its result, flags) or None."""
    out = {}
    for k in range(1, 7):
        x = next((y for y in c["rows"] if y["path"] and y["path"].startswith(f"/row/{k}/")), None)
        if x is None or x["scenario"] is None:
            out[k] = None
            continue
        m = re.search(r"row: (\d+)", x["scenario"]["name"] or "")
        out[k] = (m.group(1) if m else "none", x["scenario"]["result"], x["flags"])
    return out


def quoted(names):
    return ", ".join('"' + n + '"' for n in names)


