def load(path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def runs(lane):
    root = RESULTS / lane
    if not root.is_dir():
        return []
    out = []
    for d in sorted((p for p in root.iterdir() if p.is_dir() and p.name.isdigit()), key=lambda p: int(p.name)):
        out.append({
            "n": int(d.name), "dir": d, "rel": d.relative_to(RESULTS).as_posix(),
            "compare": load(d / "compare.json"), "info": load(d / "run-info.json"), "async": load(d / "asynclocal.json"),
        })
    return out


def secs(v):
    return "-" if v is None else f"{v:.3f}"


def row_for(compare, test):
    """The row of a test by its class-qualified name (from the TRX's test definitions) or by its display name."""
    if not compare:
        return None
    return next((r for r in compare["rows"] if r.get("fqn") == test), None) or next((r for r in compare["rows"] if r["test"] == test), None)


def spec_bytes(run):
    path = run["dir"] / "reports-files.txt"
    if not path.exists():
        return "-"
    for line in path.read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if len(parts) == 2 and parts[1] == "Specifications.html":
            return parts[0]
    return "none"


CRASH = re.compile(r"Unhandled exception|\[FATAL ERROR\]|Catastrophic failure|Test host process crashed|aborted", re.I)


def console_errors(run):
    path = run["dir"] / "console.txt"
    if not path.exists():
        return []
    seen = []
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.strip()
        if CRASH.search(line) and line not in seen:
            seen.append(line)
    return seen


def cell(r):
    if r is None:
        return "not in the TRX"
    s = r["scenario"]
    if s is None:
        return "**no scenario**"
    return f"{s['result']} as \"{s['name']}\""


